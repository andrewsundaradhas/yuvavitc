// Renders ASSET_INVENTORY.md from scripts/out/inventory.json + path-map.json + optimize-report.json.
import fs from 'node:fs'
const inv = JSON.parse(fs.readFileSync('scripts/out/inventory.json', 'utf8'))
const map = JSON.parse(fs.readFileSync('scripts/out/path-map.json', 'utf8'))
const rep = Object.fromEntries(JSON.parse(fs.readFileSync('scripts/out/optimize-report.json', 'utf8')).map((r) => [r.from, r]))
const used = new Set(inv.files.filter((f) => f.referenced).map((f) => f.file))
const kb = (b) => (b >= 1048576 ? `${(b / 1048576).toFixed(1)} MB` : `${Math.round(b / 1024)} KB`)
const t = inv.totals

const ref = inv.files.filter((f) => f.referenced)
const twins = inv.files.filter((f) => !f.referenced && f.duplicates.some((d) => used.has(d)))
const uncertain = inv.files.filter((f) => !f.referenced && !f.duplicates.some((d) => used.has(d)))
const fmt = (f) => (f.ext === 'webp' && f.realFormat !== 'webp' ? `**${f.realFormat} (fake .webp)**` : f.realFormat)

let md = `# ASSET_INVENTORY.md — public/images

Generated by \`scripts/image-inventory.mjs\` + \`scripts/inventory-md.mjs\` on ${inv.generated.slice(0, 10)}, **before any deletion**.
Reference sources scanned: every string value exported from \`src/data.js\` (loaded as a module, so \`img()\` helper output is included), every \`.js/.jsx/.css\` file in \`src/\`, and \`index.html\`.
Duplicates were detected by MD5 content hash. "Real format" comes from the file's magic bytes, not its extension.

## Totals
| | Files | Size |
|---|---|---|
| All files in public/images | ${t.files} | ${t.totalMB} MB |
| Referenced by the site | ${t.referencedFiles} | ${t.referencedMB} MB |
| Unused: byte-identical twin of a referenced file | ${twins.length} | ${kb(twins.reduce((s, f) => s + f.bytes, 0))} |
| Unused: no twin (owner approved backup and delete, D-017) | ${uncertain.length} | ${kb(uncertain.reduce((s, f) => s + f.bytes, 0))} |
| Fake \`.webp\` (JPEG inside) | ${t.fakeWebp} | |
| Referenced and over 300 KB | ${t.over300KB} | |
| EXIF-rotated (orientation baked in during conversion) | ${t.exifRotated} | |
| References pointing to a missing file | ${inv.missingReferences.length} | |

Also outside \`public/images\`: \`public/og.jpg\` (90 KB, social preview, kept as JPEG for scrapers), \`public/favicon.png\` (43 KB, kept). StaggeredMenu has a default \`logoUrl\` of \`/src/assets/logos/reactbits-gh-white.svg\`, which is never used because Nav passes its own logo; that file doesn't exist.

## A. Referenced (${ref.length}) → replaced by optimized WebP in \`public/img/\`
| Original | Real format | Size | Pixels | Referenced from | Optimized | Variants (KB) |
|---|---|---|---|---|---|---|
${ref.map((f) => { const r = rep[f.file]; return `| ${f.file} | ${fmt(f)} | ${kb(f.bytes)} | ${f.width}×${f.height}${f.orientation > 1 ? ` (EXIF ${f.orientation})` : ''} | ${f.refs.slice(0, 2).join('<br>')}${f.refs.length > 2 ? ` +${f.refs.length - 2}` : ''} | \`${map['/images/' + f.file]}\` | ${r.to.map((x) => `${x.w}w ${x.kb}`).join(' · ')} |` }).join('\n')}

## B. Unused: byte-identical twins of referenced files (${twins.length}). Safe to remove.
| File | Size | Identical to (referenced) |
|---|---|---|
${twins.map((f) => `| ${f.file} | ${kb(f.bytes)} | ${f.duplicates.filter((d) => used.has(d)).join(', ')} |`).join('\n')}

## C. Unused, no twin (${uncertain.length}). Owner decision: back up to \`D:\\yuvavitc-image-backup\`, then delete (D-017).
| File | Real format | Size | Pixels | Note |
|---|---|---|---|---|
${uncertain.map((f) => `| ${f.file} | ${fmt(f)} | ${kb(f.bytes)} | ${f.width}×${f.height} | ${/thithikum-diwali-2026-(7|8|9|1[0-2])/.test(f.file) ? 'Extra Diwali photo; the event shows 0–6' : /^team-/.test(f.file) ? 'Team photo with no team entry' : /^\d\d-/.test(f.file) ? 'Older small version of an event photo' : ''} |`).join('\n')}
`
fs.writeFileSync('ASSET_INVENTORY.md', md)
console.log('ASSET_INVENTORY.md written', { referenced: ref.length, twins: twins.length, uncertain: uncertain.length })
