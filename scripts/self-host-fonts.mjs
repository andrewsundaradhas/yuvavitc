// Improvement #5: self-host the Google Fonts the site uses (latin + latin-ext only).
// Reads the Google CSS saved at scratch/fonts/google.css (fetch it with a modern browser UA to get woff2),
// downloads each woff2 into public/fonts/, and writes src/fonts.css with local URLs. Re-run if the font list changes.
import fs from 'node:fs'
import path from 'node:path'
import crypto from 'node:crypto'

const css = fs.readFileSync(process.argv[2] || 'scratch/fonts/google.css', 'utf8')
const KEEP = new Set(['latin', 'latin-ext'])
const blocks = [...css.matchAll(/\/\* ([a-z-]+) \*\/\s*(@font-face\s*{[^}]*})/g)].filter((m) => KEEP.has(m[1]))
fs.mkdirSync('public/fonts', { recursive: true })
const files = new Map()
let out = '/* Self-hosted Google Fonts (latin + latin-ext). Generated by scripts/self-host-fonts.mjs — do not edit by hand. */\n'
for (const [, subset, block] of blocks) {
  const family = block.match(/font-family: '([^']+)'/)[1]
  const style = block.match(/font-style: (\w+)/)[1]
  const url = block.match(/url\((https:[^)]+)\)/)[1]
  if (!files.has(url)) {
    const slug = family.toLowerCase().replace(/[^a-z0-9]+/g, '-')
    const name = `${slug}-${style}-${subset}-${crypto.createHash('md5').update(url).digest('hex').slice(0, 6)}.woff2`
    const res = await fetch(url)
    if (!res.ok) throw new Error(`${res.status} ${url}`)
    fs.writeFileSync(path.join('public/fonts', name), Buffer.from(await res.arrayBuffer()))
    files.set(url, name)
  }
  out += `/* ${subset} */\n` + block.replace(url, `/fonts/${files.get(url)}`) + '\n'
}
fs.writeFileSync('src/fonts.css', out)
const kb = [...files.values()].reduce((s, f) => s + fs.statSync(path.join('public/fonts', f)).size, 0) / 1024
console.log(`${blocks.length} @font-face, ${files.size} files, ${Math.round(kb)} KB`)
console.log([...files.values()].join('\n'))
